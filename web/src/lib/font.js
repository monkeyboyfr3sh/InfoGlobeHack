function toColumns(s) {
  const rows = s.split('|');
  const cols = [];
  for (let x = 0; x < rows[0].length; x++) cols.push(rows.map((r) => r[x] === '#'));
  return cols;
}

export const GLYPHS = new Map(Object.entries(TABLE).map(([k, s]) => [Number(k), toColumns(s)]));
const BLANK = toColumns(TABLE[0x20]);

/** Columns of a glyph. Codes the globe can't draw show as a blank cell. */
export function glyph(code) {
  return GLYPHS.get(code) || BLANK;
}
