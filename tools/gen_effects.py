"""Generate the firmware effect table from docs/effects.json (the single source of truth).

Usage: python tools/gen_effects.py            # rewrite hello_world/main/src/globe_effects.c
       python tools/gen_effects.py --annotate # also (re)add group/durationMs/sameAs to effects.json
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'docs', 'effects.json')
OUT = os.path.join(ROOT, 'hello_world', 'main', 'src', 'globe_effects.c')

# Gallery groups (plan section 4.3) and rough entrance lengths, to be calibrated from video.
GROUPS = {
    'Slides': [0, 1, 2, 4, 5, 6, 7], 'Fades': [3], 'Wipers': [12, 13, 14, 20, 21, 37],
    'Vertical': [16, 17, 18, 19, 24, 25], 'Build-ups': [8, 9, 10, 11],
    'Letter swaps': [15, 22, 23], 'Drop & pluck': list(range(26, 34)), 'Dissolves': [34, 35, 36],
}
DURATION_MS = {0: 1500, 1: 1500, 2: 1500, 3: 1500, 4: 1500, 5: 1500, 6: 2000, 7: 2000,
               8: 1000, 9: 1000, 10: 1000, 11: 1000, 12: 1000, 13: 1000, 14: 1600, 15: 4000,
               16: 1200, 17: 1200, 18: 1200, 19: 1200, 20: 1000, 21: 1000, 22: 1500, 23: 5000,
               24: 1600, 25: 1600, 26: 2400, 27: 2400, 28: 2400, 29: 2400, 30: 2400, 31: 2400,
               32: 2400, 33: 2400, 34: 2500, 35: 1600, 36: 3000, 37: 2000}
SAME_AS = {4: 0, 5: 1, 7: 6, 20: 12, 21: 13}   # "(B)" twins: no visible difference


def c_utf8(s):
    """C string literal holding the UTF-8 bytes of s (non-ASCII as octal escapes)."""
    out = []
    for b in s.encode('utf-8'):
        ch = chr(b)
        out.append(ch if 32 <= b < 127 and ch not in '"?' and b != 92 else '\\%03o' % b)
    return '"' + ''.join(out) + '"'


def main():
    doc = json.load(open(SRC, encoding='utf-8'))
    fx = doc['effects']
    group_of = {i: g for g, ids in GROUPS.items() for i in ids}
    if '--annotate' in sys.argv:
        for k, v in fx.items():
            i = int(k)
            v['group'] = group_of[i]
            v['durationMs'] = DURATION_MS[i]
            if i in SAME_AS:
                v['sameAs'] = SAME_AS[i]
            else:
                v.pop('sameAs', None)
        with open(SRC, 'w', encoding='utf-8', newline='\n') as f:
            json.dump(doc, f, ensure_ascii=False, indent=2)
            f.write('\n')
    rows = []
    for k in sorted(fx, key=int):
        v = fx[k]
        rows.append('    { %2d, %-44s %-18s %5d, %2d },' % (
            int(k), c_utf8(v['name']) + ',', c_utf8(v['group']) + ',', v['durationMs'], v.get('sameAs', -1)))
    src = ('/* Generated by tools/gen_effects.py from docs/effects.json. Do not edit by hand. */\n'
           '#include "globe_frame.h"\n\n'
           'const globe_effect_info_t g_globe_effects[] = {\n' + '\n'.join(rows) + '\n};\n\n'
           'const int g_globe_effect_count = sizeof(g_globe_effects) / sizeof(g_globe_effects[0]);\n')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(src)
    print('wrote', os.path.relpath(OUT, ROOT), len(rows), 'effects')


if __name__ == '__main__':
    main()
